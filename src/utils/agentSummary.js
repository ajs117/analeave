import { getHolidays } from '../data/holidays.js'
import { computeBalances, currentViewYear, dateToLocalISO, getYearWindow, parseLocalISO, workingDaysInRange } from './leaveService.js'

const HOLIDAY_BASIS = 'Working days exclude weekends and UK (England & Wales) bank holidays for both people; HK holidays are listed for reference only and do not reduce leave.'

const addDays = (iso, n) => { const d = parseLocalISO(iso); d.setDate(d.getDate() + n); return dateToLocalISO(d) }
const overlaps = (e, from, to) => !(e.end < from || e.start > to)

function leaveYear(data, key, viewYear, todayIso){
  const p = data.people[key]
  const b = computeBalances(data, viewYear)[key]
  const yesterday = addDays(todayIso, -1)
  const taken = data.entries
    .filter(e => e.person === key && overlaps(e, b.yearStart, b.yearEnd) && e.start <= yesterday)
    .reduce((s, e) => {
      const start = e.start < b.yearStart ? b.yearStart : e.start
      const end = [e.end, b.yearEnd, yesterday].sort()[0]
      return start <= end ? s + workingDaysInRange(start, end) : s
    }, 0)
  return {
    start: b.yearStart,
    end: b.yearEnd,
    base_entitlement: p.entitlement,
    carried_over_in: b.carry,
    purchased: b.purchased,
    earned: b.earned,
    total_entitlement: b.entitlement,
    booked_total: b.used,
    already_taken: taken,
    booked_future: b.used - taken,
    remaining_unbooked: b.remaining,
    remaining_hours: b.remainingHours,
    lost_at_year_end_if_unbooked: b.mustUse,
  }
}

export function findOpportunities(data, { person = 'both', from, to, maxLeaveDays = 5, minDaysOff = 4, limit = 10 }){
  const holidays = new Set()
  for(let y = Number(from.slice(0, 4)); y <= Number(to.slice(0, 4)); y++) getHolidays(y, 'UK').forEach(d => holidays.add(d))
  const people = person === 'both' ? ['me', 'wife'] : [person]
  const onLeave = (iso) => people.every(k => data.entries.some(e => e.person === k && e.start <= iso && iso <= e.end))

  const days = []
  for(let iso = from; iso <= to; iso = addDays(iso, 1)){
    const dow = parseLocalISO(iso).getDay()
    days.push({ iso, off: dow === 0 || dow === 6 || holidays.has(iso) || onLeave(iso), holiday: holidays.has(iso) })
  }

  const candidates = []
  for(let s = 0; s < days.length; s++){
    if(s > 0 && days[s - 1].off) continue
    let cost = 0
    for(let e = s; e < days.length && e - s < 24; e++){
      if(!days[e].off) cost++
      if(cost > maxLeaveDays) break
      const length = e - s + 1
      if(cost === 0 || length < minDaysOff) continue
      if(e + 1 < days.length && days[e + 1].off) continue
      const book = days.slice(s, e + 1).filter(d => !d.off)
      candidates.push({
        days_off_in_a_row: length,
        leave_days_needed: cost,
        off_from: days[s].iso,
        off_to: days[e].iso,
        book_leave_from: book[0].iso,
        book_leave_to: book[book.length - 1].iso,
        bank_holidays_used: days.slice(s, e + 1).filter(d => d.holiday).map(d => d.iso),
      })
    }
  }
  candidates.sort((a, b) => b.days_off_in_a_row / b.leave_days_needed - a.days_off_in_a_row / a.leave_days_needed || b.days_off_in_a_row - a.days_off_in_a_row)
  const picked = []
  for(const c of candidates){
    if(picked.some(p => !(c.off_to < p.off_from || c.off_from > p.off_to))) continue
    picked.push(c)
    if(picked.length >= limit) break
  }
  return picked.sort((a, b) => a.off_from.localeCompare(b.off_from))
}

export function buildAgentSummary(data, today = new Date()){
  const todayIso = dateToLocalISO(today)
  const horizon = dateToLocalISO(getYearWindow(today.getMonth() + 1, today).yearEnd)
  const people = {}
  for(const key of Object.keys(data.people)){
    const p = data.people[key]
    const viewYear = currentViewYear(p.yearStartMonth, today)
    people[key] = {
      label: p.label,
      leave_year_starts_month: p.yearStartMonth,
      base_entitlement_days: p.entitlement,
      hours_per_day: Number(p.hoursPerDay) || 8,
      carry_over_limit_days: p.carryOverLimit,
      max_purchased_days: p.maxPurchased ?? null,
      max_earned_days: p.maxEarned ?? null,
      current_leave_year: leaveYear(data, key, viewYear, todayIso),
      next_leave_year: leaveYear(data, key, viewYear + 1, todayIso),
    }
  }
  const years = [today.getFullYear(), today.getFullYear() + 1, today.getFullYear() + 2]
  return {
    about: 'Annual leave data for two people ("me" and "wife"), generated by the Analeave app each time the data changes and at least daily when the app is opened. Use it to give leave-planning advice.',
    generated_on: todayIso,
    rules: [
      HOLIDAY_BASIS,
      'Unused days above carry_over_limit_days are lost at the end of each leave year (see lost_at_year_end_if_unbooked).',
      'remaining_unbooked can be negative, meaning more leave is booked than is available.',
      'already_taken / booked_future are relative to generated_on.',
    ],
    people,
    leave: [...data.entries]
      .sort((a, b) => a.start.localeCompare(b.start) || a.person.localeCompare(b.person))
      .map(e => ({ person: e.person, start: e.start, end: e.end, working_days: workingDaysInRange(e.start, e.end), note: e.note || '' })),
    bank_holidays: Object.fromEntries(['UK', 'HK'].map(r => [r, Object.fromEntries(years.map(y => [y, getHolidays(y, r)]))])),
    suggested_breaks_together: {
      description: `Windows from ${todayIso} to ${horizon} where up to 5 leave days (for both) bridge weekends, UK bank holidays and already-booked leave into 4+ days off, best value first per window.`,
      windows: findOpportunities(data, { from: todayIso, to: horizon }),
    },
  }
}
